export const translateDistrict = (
  district: string | undefined,
  language: string
): string => {
  if (!district) return "";

  const lang = language.startsWith("si") ? "si" : "en";

  // Normalize input
  const normalizedInput = district
    .toLowerCase()
    .replace(/-/g, " ")
    .trim();

  // Find matching key
  const key = Object.keys(districtTranslations).find(
    k =>
      k.toLowerCase()
        .replace(/-/g, " ")
        .trim() === normalizedInput
  );

  return key ? districtTranslations[key][lang] : district;
};

export const translateDivision = (
  division: string | undefined,
  language: string
): string => {
  if (!division) return "";

  return (
    divisionTranslations[division]?.[
      language === "si" ? "si" : "en"
    ] || division
  );
};